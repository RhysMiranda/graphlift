"""Generate a Syn Env graph and save it in graphlift's plain on-disk format.

    python scripts/make_synenv.py --mode balanced --seed 2 --out runs/synenv_balanced

Output layout (what graphlift.load_dir reads):
    nodes/<type>.csv   one row per node: id + attributes
    edges.csv          src_type, src_id, relation, dst_type, dst_id
    graphlift.json     which node type is the target, which column is the label,
                       which column holds leakage-safe groups, which attributes
                       are labels in disguise and must never be features.

Groups: union-find over every NON-camouflage edge. Camouflage edges are real,
observable edges, but they are what a fraudster adds to blend in, so following
them would merge every ring and benign cluster into one giant component. This
mirrors how Syn Env's own exporter builds its grouped split.
"""
from __future__ import annotations

import argparse
import json
import os
import sys
from collections import defaultdict

import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from synenv import GenConfig, generate  # noqa: E402  (run from your Syn Env checkout)

# Node attributes that are ground truth, not observations. A bank does not get
# to see `is_mule` on an account; including them would hand any model the answer.
LABEL_ATTRS = {
    "application": ["fraud_bool", "fraud_true", "typology"],
    "bank": ["is_mule"],
    "document": ["is_forged"],
    "employee": ["is_corrupt", "prior_fraud_flags"],
    "transaction": ["is_laundering"],
    "device": ["fraud_count"],
}


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--mode", choices=["balanced", "rare"], default="balanced")
    p.add_argument("--seed", type=int, default=2)
    p.add_argument("--pool", default=None,
                   help="BAF-format feature rows to sample from (default: Syn Env's BAF path)")
    p.add_argument("--out", default=None)
    a = p.parse_args()
    out = a.out or f"runs/synenv_{a.mode}_s{a.seed}"

    mk = GenConfig.rare if a.mode == "rare" else GenConfig.balanced
    cfg = mk(seed=a.seed, baf_csv=a.pool, baf_holdout=None) if a.pool else mk(seed=a.seed)
    g = generate(cfg)

    # -- leakage-safe groups: union-find over non-camouflage edges -------------
    parent: dict = {}

    def find(x):
        parent.setdefault(x, x)
        while parent[x] != x:
            parent[x] = parent[parent[x]]
            x = parent[x]
        return x

    def union(x, y):
        rx, ry = find(x), find(y)
        if rx != ry:
            parent[rx] = ry

    rows = []
    for st, rel, dt, sid, did, attrs in g.edges:
        rows.append((st, sid, rel, dt, did, int(bool(attrs.get("camouflage")))))
        if not attrs.get("camouflage"):
            union((st, sid), (dt, did))

    os.makedirs(os.path.join(out, "nodes"), exist_ok=True)
    edges = pd.DataFrame(rows, columns=["src_type", "src_id", "relation", "dst_type",
                                        "dst_id", "camouflage"])
    edges.drop(columns="camouflage").to_csv(os.path.join(out, "edges.csv"), index=False)
    # Kept separately for diagnostics only. graphlift never reads it.
    edges[edges.camouflage == 1].to_csv(os.path.join(out, "_camouflage_edges.csv"), index=False)

    comp_ids: dict = {}
    for ntype, nodes in g.nodes.items():
        df = pd.DataFrame.from_dict(nodes, orient="index")
        df.index.name = "id"
        df = df.reset_index()
        if ntype == "application":
            roots = [find(("application", i)) for i in df["id"]]
            df["group"] = [comp_ids.setdefault(r, f"g{len(comp_ids):05d}") for r in roots]
        df.to_csv(os.path.join(out, "nodes", f"{ntype}.csv"), index=False)

    meta = {
        "name": f"Syn Env ({a.mode}, seed {a.seed})",
        "target": "application",
        "label": "fraud_bool",
        "group": "group",
        "time": "applied_at",
        "breakdown": "typology",
        "exclude": LABEL_ATTRS,
        "notes": "Generated by Syn Env. Features sampled from "
                 + (a.pool or "the BAF dataset") + ".",
    }
    with open(os.path.join(out, "graphlift.json"), "w") as f:
        json.dump(meta, f, indent=2)
    s = g.summary()
    with open(os.path.join(out, "summary.json"), "w") as f:
        json.dump(s, f, indent=2, default=str)
    print(json.dumps({k: s[k] for k in ("n_applications", "n_fraud_applications",
                                        "n_fraud_ground_truth", "fraud_rate",
                                        "n_camouflage_edges", "by_typology")}, indent=1))
    print("groups:", len(comp_ids), "->", out)


if __name__ == "__main__":
    main()
